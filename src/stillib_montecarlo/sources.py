from collections.abc import Callable, Sequence
from dataclasses import dataclass
from typing import Any

import numpy as np


class Source:
    """Base class for sources of uncertain variables. Subclasses must implement the sample_once method."""

    def sample_once(self, rng: np.random.Generator) -> Any:
        raise NotImplementedError("sample_once must be implemented in subclasses.")


@dataclass(frozen=True, slots=True)
class Constant(Source):
    """A source that always returns the same value."""

    value: Any

    def sample_once(self, rng: np.random.Generator) -> Any:
        return self.value


@dataclass(frozen=True, slots=True)
class Empirical(Source):
    """A source that returns values sampled with replacement from an empirical distribution."""

    values: Sequence[Any]

    def sample_once(self, rng: np.random.Generator) -> Any:
        return rng.choice(self.values)


@dataclass(frozen=True, slots=True)
class Model(Source):
    """A source that returns values generated by a model, i.e. any callable taking only an RNG as its argument."""

    model: Callable[[np.random.Generator], Any]

    def sample_once(self, rng: np.random.Generator) -> Any:
        return self.model(rng)
